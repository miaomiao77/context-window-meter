"""Embed the pure core into each entry point; no runtime global/module handshake."""
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[1]
core, marker, _ = (root / 'core.js').read_text().partition('// Node test export; excluded from browser bundles.')
if not marker:
    raise SystemExit('Core factory boundary missing')
for name in ['page_script.js', 'content.js']:
    source = (root / 'src' / name).read_text()
    bundle = ('/* Generated by scripts/build.py; edit core.js and src/' + name + '. */\n'
              '(function () {\n' + core + '\nconst C = Object.freeze(createCWMCore());\n' + source + '\n})();\n')
    output = root / name
    if '--check' in sys.argv:
        if not output.exists() or output.read_text() != bundle:
            raise SystemExit(f'{name} is stale: run npm run build')
    else:
        output.write_text(bundle)
print('Browser bundles checked' if '--check' in sys.argv else 'Browser bundles built')
