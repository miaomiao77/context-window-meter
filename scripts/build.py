"""Embed the pure core into each entry point; no runtime global/module handshake."""
from pathlib import Path
import sys
import subprocess

root = Path(__file__).resolve().parents[1]
core, marker, _ = (root / 'core.js').read_text().partition('// Node test export; excluded from browser bundles.')
if not marker:
    raise SystemExit('Core factory boundary missing')
scanner, marker, _ = (root / 'scanner.js').read_text().partition('// Node test export; excluded from browser bundles.')
if not marker:
    raise SystemExit('Scanner factory boundary missing')
for name in ['page_script.js', 'content.js']:
    source = (root / 'src' / name).read_text()
    tokenizer = ''
    if name == 'content.js':
        packed = subprocess.check_output([str(root / 'node_modules/.bin/esbuild'), 'src/local-tokenizer.mjs',
            '--bundle', '--format=iife', '--global-name=localBpe', '--minify',
            '--target=chrome110', '--charset=utf8'], cwd=root).decode()
        tokenizer = ('let bpeCount; function countLocalTokens(s) { if (!bpeCount) {\n' +
                     packed + '\nbpeCount = localBpe.count; } return bpeCount(s); }\n')
    bundle = ('/* Generated by scripts/build.py; edit core.js and src/' + name + '. */\n'
              '(function () {\n' + core + '\nconst C = Object.freeze(createCWMCore());\n' + tokenizer + (scanner if name == 'content.js' else '') + '\n' + source + '\n})();\n')
    output = root / name
    if '--check' in sys.argv:
        if not output.exists() or output.read_text() != bundle:
            raise SystemExit(f'{name} is stale: run npm run build')
    else:
        output.write_text(bundle)
print('Browser bundles checked' if '--check' in sys.argv else 'Browser bundles built')
